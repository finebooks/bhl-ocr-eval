# /// script
# requires-python = ">=3.10"
# dependencies = ["huggingface-hub"]
# ///
"""Emit the `hf jobs uv run` command for every job in a launch plan.

The commands are DERIVED from the plan, never typed. A launch line that drops
`--revision` or `--id-column PageID` does not corrupt anything silently — scoring fails
closed on a page-set mismatch — but it fails *after* the GPU time is spent, and the
longest job here is six and a half hours. Generating the commands means the plan and the
run cannot disagree.

Each command also carries `--model-revision <sha>`, resolved here and passed through to
`vllm serve --revision`. The board's claim is a pinned model revision; without this the
sha is only ever read back from the Hub afterwards, which is not guaranteed to be what
vLLM actually loaded across a launch window spanning several hours.

The resolved shas are STICKY: they are written to `model-revisions.json` beside the plan
and reused on every later run, so regenerating the commands cannot silently re-pin the
board to a newer checkpoint. `--refresh` re-resolves deliberately.

  uv run scripts/emit_launch_commands.py                      # print
  uv run scripts/emit_launch_commands.py --out data/full-2026-08/jobs-launch.sh
"""

import argparse
import json
import pathlib
import shlex

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Jobs whose driver is not one of ours; they take a different argument surface and are
# emitted as comments for a human to run, rather than silently mis-generated.
FOREIGN = {"uv-scripts/ocr/surya-ocr.py", "uv-scripts/ocr/pp-ocrv6.py"}


def resolve_model_revisions(models, cache_path, refresh):
    """model id -> checkpoint sha, sticky across runs.

    A pin that moves when you regenerate is not a pin. Anything already recorded is
    reused verbatim; only models absent from the cache are looked up, unless --refresh.
    """
    cached = json.loads(cache_path.read_text()) if cache_path.exists() else {}
    wanted = [m for m in models if refresh or m not in cached]
    if wanted:
        from huggingface_hub import HfApi

        api = HfApi()
        for model in wanted:
            cached[model] = api.model_info(model).sha
            print(f"  resolved {model} -> {cached[model]}")
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(json.dumps(cached, indent=2, sort_keys=True) + "\n")
    return cached


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", default=str(ROOT / "data" / "full-2026-08" / "launch-plan.json"))
    ap.add_argument("--out", default=None)
    ap.add_argument("--refresh", action="store_true",
                    help="re-resolve every model sha, overwriting the sticky record")
    args = ap.parse_args()

    plan_path = pathlib.Path(args.plan)
    plan = json.loads(plan_path.read_text())
    b = plan["benchmark"]
    timeout = plan["operational"]["timeout"]
    out_tpl = plan["output"]

    revisions_path = plan_path.parent / "model-revisions.json"
    served = [j["model"] for j in plan["jobs"]
              if j["driver"] not in FOREIGN
              and not j.get("status", "").startswith("ALREADY")]
    revisions = resolve_model_revisions(served, revisions_path, args.refresh)

    lines = [
        "#!/bin/bash",
        "# GENERATED by scripts/emit_launch_commands.py — do not edit.",
        f"# plan: {args.plan}  (run_id: {plan['run_id']})",
        f"# benchmark: {b['repo']}@{b['revision']}  ({b['rows']} rows)",
        f"# fingerprint: {b['page_set_fingerprint']}",
        f"# model revisions: {revisions_path.name}",
        "#",
        "# Every command pins the revision and sets --id-column PageID. The id must BE the",
        "# PageID: scoring joins ground truth on it, and saturate keys output rows by `id`.",
        "# --model-revision pins the SERVED checkpoint (vllm serve --revision).",
        "set -euo pipefail",
        "",
    ]

    launched, skipped = 0, 0
    for job in plan["jobs"]:
        slug = job["driver"].replace("-port.py", "").replace(".py", "")
        if job.get("status", "").startswith("ALREADY"):
            lines += [f"# {job['model']}: {job['status']} — not re-emitted", ""]
            skipped += 1
            continue
        if job["driver"] in FOREIGN:
            lines += [
                f"# {job['model']} — foreign driver ({job['driver']}), different argument surface.",
                "#   Run by hand: positional <input_dataset> <output_dataset>, --max-samples/--shuffle",
                "#   rather than --shard, and NO --revision flag exists on this path (see the plan's",
                f"#   provenance caveat). flavor={job['flavor']}",
                "",
            ]
            skipped += 1
            continue

        cmd = [
            "hf", "jobs", "uv", "run", "--detach",
            "--flavor", job["flavor"],
            "-s", "HF_TOKEN",
            "--timeout", timeout,
            "--image", plan["image"]["exceptions"].get(slug, plan["image"]["pin"]),
            f"drivers/{job['driver']}",
            "--",
            "--input-dataset", b["repo"],
            "--revision", b["revision"],
            "--image-column", "image",
            "--id-column", "PageID",
            "--model-revision", revisions[job["model"]],
            "--output", out_tpl.format(model_slug=slug),
        ]
        lines += [f"# {job['model']}  ~{job.get('est_hours', '?')}h  ~${job.get('est_usd', '?')}",
                  " ".join(shlex.quote(c) for c in cmd), ""]
        launched += 1

    text = "\n".join(lines)
    if args.out:
        p = pathlib.Path(args.out)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        p.chmod(0o755)
        print(f"{launched} commands -> {p}  ({skipped} skipped: already launched or foreign driver)")
    else:
        print(text)


if __name__ == "__main__":
    main()
